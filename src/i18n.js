// Values passed in vars are inserted as given, so callers escape user text first.
function translator(lang) {
  const dict = texts[lang] || texts.uz;
  return (key, vars = {}) => {
    const s = dict[key] ?? texts.en[key] ?? key;
    return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  };
}

function pickLang(req) {
  const fromCookie = (req.get('cookie') || '').match(/(?:^|;\s*)lang=(\w+)/)?.[1];
  if (LANGS.includes(fromCookie)) return fromCookie;
  const accept = (req.get('accept-language') || '').toLowerCase();
  if (accept.startsWith('ru')) return 'ru';
  if (accept.startsWith('en')) return 'en';
  return 'uz';
}

